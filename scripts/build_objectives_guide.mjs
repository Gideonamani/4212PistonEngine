// Writes docs/lesson-objectives.md from the lesson packs (purpose, coreIdea, outcomes, syllabusNote) and data/curriculum-storyline.json.
//   node scripts/build_objectives_guide.mjs           write the page
//   node scripts/build_objectives_guide.mjs --check   exit 1 if the page on disk is out of date (scripts/test_lesson_objectives.mjs does this too)
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { outcomeSections } from '../src/data/outcomes.mjs';

export const GUIDE_PATH = 'docs/lesson-objectives.md';

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const two = (number) => String(number).padStart(2, '0');

/** The numbered syllabus lessons, in app order, each with the course (pack) it sits in. */
export function loadSyllabusLessons() {
  const lessons = [];
  for (const file of readJson('web/lessons-manifest.json').packs) {
    const pack = readJson(`web/${file.replace(/^\.\//, '')}`);
    for (const lesson of pack.lessons) if (lesson.sequenceNumber !== undefined && lesson.listed !== false) lessons.push({ ...lesson, course: pack.title });
  }
  return lessons.sort((a, b) => a.sequenceNumber - b.sequenceNumber);
}

export function buildGuide(lessons = loadSyllabusLessons(), storyline = readJson('data/curriculum-storyline.json')) {
  const byId = new Map(lessons.map((lesson) => [lesson.id, lesson]));
  const out = [];
  const add = (...lines) => out.push(...lines);

  add(
    '# Lesson objectives',
    '',
    '<!-- Generated by scripts/build_objectives_guide.mjs from the lesson packs. Edit the packs, then run the script; do not edit this page. -->',
    '',
    `What each of the ${lessons.length} lessons is for, and what a learner should be able to do at the end of it. The wording is the instructor's (written ${storyline.written}). It lives in the lesson packs, \`web/*-lessons.json\`, as four fields on each lesson, and this page is generated from them.`,
    '',
    '| Field | What it holds | Shown to learners |',
    '|---|---|---|',
    '| `purpose` | One sentence: what the lesson is for. | Yes, at the top of the end-of-lesson self-check |',
    '| `coreIdea` | The single thought to leave with, where there is one. | Yes, in the self-check |',
    '| `outcomes` | What a learner should be able to do, one sentence each (a heading and its sentences for a lesson with parts). | Yes: the self-check ticks them off |',
    '| `syllabusNote` | Why the lesson is in the syllabus, in the instructor\'s words. | No: for authors and reviewers |',
    '',
    '## How to use them',
    '',
    '- **Writing or reworking a lesson:** read its purpose and outcomes first. Every outcome should be taught in a step, and where it can be tested, asked in one of the lesson\'s checks. An outcome no step teaches is a gap in the lesson, not in the list.',
    '- **Changing an outcome:** edit it in the pack. A learner\'s ticks are kept per sentence, so a reworded outcome starts unticked.',
    '- **For learners:** the last screen of each lesson lists the outcomes as a "Check yourself" tick-list. The ticks are saved on the learner\'s own device and nowhere else.',
    '',
    '## The storyline',
    '',
    'The order in which the instructor wants the module to read as one story (`data/curriculum-storyline.json`), compared with the order the app uses today.',
    '',
    '| # | Step | The question it answers | Lesson | In the app |',
    '|---|---|---|---|---|',
  );
  const differs = [];
  storyline.steps.forEach((step, index) => {
    const lesson = byId.get(step.lessonId);
    const inApp = lesson ? lesson.sequenceNumber : undefined;
    if (inApp !== index + 1) differs.push(`${lesson ? lesson.title : step.lessonId} (storyline ${index + 1}, app ${inApp ?? 'missing'})`);
    add(`| ${index + 1} | ${step.label} | ${step.question} | ${lesson ? lesson.title : step.lessonId} | ${inApp === undefined ? 'missing' : `Lesson ${two(inApp)}${inApp === index + 1 ? '' : ' (differs)'}`} |`);
  });
  add('', differs.length ? `The app's lesson order differs from the storyline for: ${differs.join('; ')}.` : "The app's lesson order matches the storyline.", '', '## The lessons');

  for (const lesson of lessons) {
    add('', `### Lesson ${two(lesson.sequenceNumber)} · ${lesson.title}`, '', `\`${lesson.id}\` · ${lesson.course}`, '');
    add(`**Purpose.** ${lesson.purpose ?? '_Not written yet._'}`);
    if (lesson.coreIdea) add('', `**Core idea.** ${lesson.coreIdea}`);
    add('', lesson.outcomes?.length ? 'Learners should be able to:' : '_No outcomes written yet._', '');
    for (const section of outcomeSections(lesson.outcomes)) {
      if (section.heading) add(`**${section.heading}**`, '', ...(section.note ? [`${section.note}`, ''] : []));
      add(...section.items.map((item) => `- ${item}`), '');
    }
    if (lesson.syllabusNote) add(`_Syllabus note: ${lesson.syllabusNote}_`, '');
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = buildGuide();
  if (process.argv.includes('--check')) {
    const onDisk = fs.existsSync(GUIDE_PATH) ? fs.readFileSync(GUIDE_PATH, 'utf8').replace(/\r\n/g, '\n') : '';
    if (onDisk !== text) { console.error(`${GUIDE_PATH} is out of date: run node scripts/build_objectives_guide.mjs`); process.exit(1); }
  } else {
    fs.writeFileSync(GUIDE_PATH, text);
    console.log(`wrote ${GUIDE_PATH} (${text.length} characters)`);
  }
}
